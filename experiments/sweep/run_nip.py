"""Nothing-in-particular (NIP) SFT control on the sweep models (paper §4.7).

SFT on three neutral datasets (nip1-3: 50 everyday questions each with a normal
answer, generated by claude-sonnet-4.6; in nip_datasets/) with the sweep's SFT recipe, then the full
battery. Measures how much traits drift under fine-tuning that targets no trait.

    PG_EXPERIMENT=sweep PYTHONPATH=experiments/src python experiments/sweep/run_nip.py \
        --model Qwen/Qwen3.5-9B --dataset nip1

Results: results/<short>-sft-nip-<dataset>/ (same layout as the sweep runs).
"""
import argparse
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))

from harness import CostLedger  # noqa: E402
from harness.config import load_config, run_dir  # noqa: E402
from harness.experiment import Variant, run_experiment  # noqa: E402
from harness.train import train_sft  # noqa: E402

NIP = os.path.join(HERE, "nip_datasets")
SHORT = {"Qwen/Qwen3.5-9B": "qwen3.5-9b", "Qwen/Qwen3.5-9B-Base": "qwen3.5-9b-base",
         "nvidia/NVIDIA-Nemotron-3-Super-120B-A12B-BF16": "nemotron-3-super"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, choices=list(SHORT))
    ap.add_argument("--dataset", required=True, choices=["nip1", "nip2", "nip3"])
    args = ap.parse_args()
    cfg = load_config()
    short = SHORT[args.model]
    name = f"{short}-sft-nip-{args.dataset}"
    if os.path.exists(os.path.join(HERE, "results", name, "judged.csv")):
        print("skip", name)
        return
    items = yaml.safe_load(open(f"{NIP}/{args.dataset}/{args.dataset}_eval.yaml"))
    examples = [{"question_id": it["id"], "question": it["paraphrases"][0], "response": it["example_response"]}
                for it in items]
    hp = cfg.get("sweep", {}).get("hp_overrides", {}).get(args.model, {})
    epochs = hp.get("sft_epochs", cfg["pilot"]["sft_epochs"])
    ledger = CostLedger(name + "-train", model=args.model, meta={"dataset": args.dataset, "examples": len(examples)})
    print(f"SFT {args.model} on {len(examples)} {args.dataset} examples ({epochs} epoch(s))", flush=True)
    tr = train_sft(args.model, examples, ledger=ledger, epochs=epochs,
                   batch_size=cfg["pilot"].get("sft_batch_size"), lora_rank=cfg["pilot"]["lora_rank"], name=name)
    print(ledger.save(run_dir(name + "-train")))
    print("sampler_path:", tr.sampler_path, flush=True)
    res = run_experiment(args.model, Variant(kind="sft", trait=args.dataset, sampler_path=tr.sampler_path),
                         run_name=name, split=cfg["pilot"]["eval_split"],
                         baseline_judged=os.path.join(HERE, "results", f"{short}-baseline", "judged.csv"))
    print(res["summary_md"][-400:])


if __name__ == "__main__":
    main()
